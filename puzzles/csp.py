"""Finite-domain CSP core with two INDEPENDENT CNF encodings.

Clean-room implementation of the generate -> encode -> certify loop of
Behnamian et al., "Fair but hard: certified unique-solution puzzles
generated by language models" (Lund University). No code is taken from
that repository; only the published method is followed, and every place
where our construction could deviate is cross-checked instead of trusted:

  * encoding A ("direct"): one Boolean x[v][a] per (variable, value);
    exactly-one per variable; pairwise at-most-one for alldiff; one
    forbidden-tuple clause per disallowed tuple of a table constraint.
  * encoding B ("support"): same x[v][a]; for every table constraint each
    ALLOWED tuple gets an auxiliary support variable s_t with
    s_t -> x[v_i][t_i] for all i, plus one clause requiring at least one
    support to hold; alldiff is encoded via value-position variables
    y[a][v] (which value sits in which variable), a genuinely different
    variable scheme.

A puzzle is only certified when both encodings, solved independently,
enumerate exactly the same singleton solution set, AND the solution also
passes the direct declarative check() (predicate evaluation, no CNF at
all). Three independent paths must agree before any prompt is issued.
"""
from __future__ import annotations

import itertools

from .dpll import ClauseDB, Solver


class Constraint:
    """kind: 'alldiff' or 'table'. table: pred(*labels) -> bool."""

    __slots__ = ("kind", "scope", "pred", "meta")

    def __init__(self, kind, scope, pred=None, meta=None):
        self.kind = kind
        self.scope = tuple(scope)
        self.pred = pred
        self.meta = dict(meta or {})

    def __repr__(self):
        return f"Constraint({self.kind}, scope={self.scope}, meta={self.meta})"


def alldiff(scope, meta=None):
    return Constraint("alldiff", scope, meta=meta)


def table(scope, pred, meta=None):
    return Constraint("table", scope, pred=pred, meta=meta)


class CSP:
    def __init__(self, names, domains):
        self.names = list(names)
        self.domains = [list(d) for d in domains]
        self.index = {n: i for i, n in enumerate(self.names)}
        self.rules = []
        self.clues = []

    def add_rule(self, c):
        self.rules.append(c)

    def add_clue(self, c):
        self.clues.append(c)

    def check(self, labels, clue_ids=None):
        """Declarative check, independent of any encoding. labels: list of
        domain values, one per variable (by index)."""
        if len(labels) != len(self.names):
            return False
        cl = self.clues if clue_ids is None else [self.clues[i] for i in clue_ids]
        for c in self.rules + cl:
            vals = [labels[v] for v in c.scope]
            if c.kind == "alldiff":
                if len(set(vals)) != len(vals):
                    return False
            else:
                if not c.pred(*vals):
                    return False
        return True

    # ---------------- encoding A: direct ----------------

    def _lit_direct(self, var, val):
        return var * 100 + self.domains[var].index(val) + 1

    def encode_direct(self):
        db = ClauseDB()
        for v in range(len(self.names)):
            lits = [self._lit_direct(v, a) for a in self.domains[v]]
            db.add(lits)  # at least one
            for i, j in itertools.combinations(range(len(lits)), 2):
                db.add([-lits[i], -lits[j]])  # at most one
        for c in self.rules + self.clues:
            if c.kind == "alldiff":
                for i, j in itertools.combinations(c.scope, 2):
                    for a in self.domains[i]:
                        li = self._lit_direct(i, a)
                        lj = self._lit_direct(j, a) if a in self.domains[j] else None
                        if lj is not None:
                            db.add([-li, -lj])
            else:
                for combo in itertools.product(*(self.domains[v] for v in c.scope)):
                    if not c.pred(*combo):
                        db.add(
                            [-self._lit_direct(v, a) for v, a in zip(c.scope, combo)]
                        )
        return db

    def decode_direct(self, model):
        labels = []
        for v in range(len(self.names)):
            hit = None
            for a in self.domains[v]:
                if model.get(self._lit_direct(v, a)):
                    if hit is not None:
                        return None  # not exactly-one: not a valid solution
                    hit = a
            if hit is None:
                return None
            labels.append(hit)
        return labels

    # ---------------- encoding B: support + value-position ----------------

    def encode_support(self):
        db = ClauseDB()
        max_x = 0
        for v in range(len(self.names)):
            for a in self.domains[v]:
                max_x = max(max_x, self._lit_direct(v, a))
        next_var = max_x + 1  # auxiliary variables start after all x[v][a]

        def xlit(v, a):
            return self._lit_direct(v, a)

        if len(self.names) >= 100 or any(len(d) >= 100 for d in self.domains):
            raise ValueError("literal numbering scheme supports <100 vars/values")

        # exactly-one per variable is CSP semantics (not an encoding choice):
        # the independence between A and B lies in the CONSTRAINT encodings.
        for v in range(len(self.names)):
            lits = [xlit(v, a) for a in self.domains[v]]
            db.add(lits)
            for i, j in itertools.combinations(range(len(lits)), 2):
                db.add([-lits[i], -lits[j]])

        for c in self.rules + self.clues:
            if c.kind == "alldiff":
                # value-position scheme: y[a][w] = "variable w holds value a"
                # y[a][w] <-> x[w][a] enforced per pair; alldiff = every a in
                # the union of the scope's domains is placed in exactly one w.
                scope = list(c.scope)
                union_vals = []
                for w in scope:
                    for a in self.domains[w]:
                        if a not in union_vals:
                            union_vals.append(a)
                if len(union_vals) < len(scope):
                    # domain union too small for an alldiff of this size: UNSAT
                    db.add([next_var])
                    db.add([-next_var])  # v and not v: genuine conflict
                    continue
                for a in union_vals:
                    ys = []
                    for w in scope:
                        if a in self.domains[w]:
                            next_var += 1
                            y = next_var
                            ys.append(y)
                            x = xlit(w, a)
                            db.add([-y, x])  # y -> x
                            db.add([-x, y])  # x -> y
                    if ys:
                        for i, j in itertools.combinations(range(len(ys)), 2):
                            db.add([-ys[i], -ys[j]])  # at most one position
                        if len(union_vals) == len(scope):
                            db.add(ys)  # permutation: every value used once
            else:
                allowed = []
                for combo in itertools.product(*(self.domains[v] for v in c.scope)):
                    if c.pred(*combo):
                        next_var += 1
                        s = next_var
                        allowed.append(s)
                        for v, a in zip(c.scope, combo):
                            db.add([-s, xlit(v, a)])
                if not allowed:
                    db.add([next_var])
                    db.add([-next_var])  # v and not v: genuine conflict
                else:
                    db.add(allowed)  # at least one support
        return db

    # ---------------- certification ----------------

    def enumerate_solutions(self, cap=2):
        """Cross-checked solution enumeration, cap-bounded.

        Returns (labels_list, saturated, consistent) where labels_list is the
        common decoded solution set (from encoding A; verified against
        encoding B and check()), saturated means exhaustion was proven below
        the cap, and consistent means all three paths agreed.
        """
        sol_a, sat_a = Solver(self.encode_direct()).enumerate_models(cap)
        sols = []
        for m in sol_a:
            labels = self.decode_direct(m)
            if labels is None or not self.check(labels):
                return [], sat_a, False
            sols.append(labels)
        sol_b, sat_b = Solver(self.encode_support()).enumerate_models(cap)
        sols_b = []
        for m in sol_b:
            labels = self.decode_direct(m)
            if labels is None or not self.check(labels):
                return [], sat_b, False
            sols_b.append(labels)
        key = lambda sols: sorted(tuple(s) for s in sols)
        consistent = key(sols) == key(sols_b) and sat_a == sat_b
        return sols, sat_a, consistent

    def enumerate_solutions_direct(self, cap=2):
        """Fast path: direct encoding only, no cross-check. For generation
        loops; the FINAL certificate always goes through the dual path."""
        models, saturated = Solver(self.encode_direct()).enumerate_models(cap)
        sols = []
        for m in models:
            labels = self.decode_direct(m)
            if labels is None or not self.check(labels):
                return [], saturated, False
            sols.append(labels)
        return sols, saturated, True

    def certify_unique(self):
        """True only when: both encodings prove exactly one solution, the
        solution decodes cleanly, and it passes the declarative check."""
        sols, saturated, consistent = self.enumerate_solutions(cap=2)
        return saturated and consistent and len(sols) == 1
